import { createHash } from "node:crypto";
import type {
  Ecosystem,
  PaymentMode,
  ProjectStatus,
  ScopeGuardReport,
  TaevaEvaluationReport,
  TrustShieldReport,
  UnifiedTrustReport,
} from "@trustora/shared";
import { canonicalJson } from "../projects/agreement.js";

export interface BuildTrustReportInput {
  publicProjectId: string;
  paymentMode: PaymentMode;
  projectStatus: ProjectStatus;
  now: Date;
  evaluations: TaevaEvaluationReport[];
  totalMilestones: number;
  totalVersions: number;
  activeVersion: number;
  hasPendingProposals: boolean;
  latestScopeChange?: ScopeGuardReport;
  trustShieldReport: TrustShieldReport;
  proofTrackEvents: {
    verificationStatus: string;
    ecosystem: string;
  }[];
}

const sha256Hex = (text: string) => createHash("sha256").update(text, "utf8").digest("hex");

export const buildUnifiedTrustReport = (input: BuildTrustReportInput): UnifiedTrustReport => {
  const generatedAt = input.now.toISOString();

  let verifiedCount = 0;
  let pendingCount = 0;
  let failedCount = 0;
  const ecosystems = new Set<Ecosystem>();

  for (const ev of input.proofTrackEvents) {
    if (ev.verificationStatus === "VERIFIED") verifiedCount += 1;
    else if (ev.verificationStatus === "PENDING") pendingCount += 1;
    else if (ev.verificationStatus === "FAILED" || ev.verificationStatus === "BLOCKED") failedCount += 1;

    ecosystems.add(ev.ecosystem as Ecosystem);
  }

  const reportData = {
    publicProjectId: input.publicProjectId,
    paymentMode: input.paymentMode,
    generatedAt,
    projectStatus: input.projectStatus,
    taevaSummary: {
      totalMilestones: input.totalMilestones,
      evaluatedMilestones: input.evaluations.length,
      evaluations: input.evaluations,
    },
    scopeGuardSummary: {
      totalVersions: input.totalVersions,
      activeVersion: input.activeVersion,
      hasPendingProposals: input.hasPendingProposals,
      latestScopeChange: input.latestScopeChange,
    },
    trustShieldSummary: input.trustShieldReport,
    proofTrackSummary: {
      totalEvents: input.proofTrackEvents.length,
      verifiedCount,
      pendingCount,
      failedCount,
      ecosystemsInvolved: Array.from(ecosystems),
    },
    disclaimer:
      "This is an advisory trust and verification report generated by TRUSTORA. AI evaluation reports and TrustShield heuristics are informative and non-binding, and do not automatically release or refund funds.",
  };

  const canonical = canonicalJson(reportData);
  const verifiableReportHash = sha256Hex(canonical);

  return {
    ...reportData,
    verifiableReportHash,
  };
};
